import struct, os

def float_to_hex(f):
    return format(struct.unpack('>I', struct.pack('>f', f))[0], '08X')

# E2M1 decode table: code -> float value
E2M1 = {
    0x0: 0.0,  0x1: 0.5,  0x2: 1.0,  0x3: 1.5,
    0x4: 2.0,  0x5: 3.0,  0x6: 4.0,  0x7: 6.0,
    0x8: -0.0, 0x9: -0.5, 0xA: -1.0, 0xB: -1.5,
    0xC: -2.0, 0xD: -3.0, 0xE: -4.0, 0xF: -6.0,
}

def compute_mxfp4_mac(packed_byte, scale_code, b0, b1):
    """Compute expected MAC output for MXFP4."""
    lo_nib = packed_byte & 0xF        # even element
    hi_nib = (packed_byte >> 4) & 0xF  # odd element
    decoded_0 = E2M1[lo_nib]
    decoded_1 = E2M1[hi_nib]
    scale = 2.0 ** (scale_code - 127)  # E8M0 decode
    prod_0 = decoded_0 * scale * b0
    prod_1 = decoded_1 * scale * b1
    result = prod_0 + prod_1
    print(f"  MX: packed=0x{packed_byte:02X} lo={lo_nib}({decoded_0}) hi={hi_nib}({decoded_1}) "
          f"scale=2^{scale_code-127}={scale} B=[{b0},{b1}] -> {prod_0}+{prod_1} = {result}")
    return result

def compute_nvfp4_mac(packed_byte, bscale_code, tensor_scale, b0, b1):
    """Compute expected MAC output for NVFP4."""
    lo_nib = packed_byte & 0xF
    hi_nib = (packed_byte >> 4) & 0xF
    decoded_0 = E2M1[lo_nib]
    decoded_1 = E2M1[hi_nib]
    # FP8 E4M3 decode (code 0x38 = exp=7,man=0 -> 1.0; code 0x40 = exp=8,man=0 -> 2.0)
    exp4 = (bscale_code >> 3) & 0xF
    man3 = bscale_code & 0x7
    sign = (bscale_code >> 7) & 1
    if exp4 == 0:
        bscale_val = (man3 / 8.0) * (2.0 ** (-6))
    else:
        bscale_val = (1.0 + man3 / 8.0) * (2.0 ** (exp4 - 7))
    if sign:
        bscale_val = -bscale_val
    eff_scale = bscale_val * tensor_scale
    prod_0 = decoded_0 * eff_scale * b0
    prod_1 = decoded_1 * eff_scale * b1
    result = prod_0 + prod_1
    print(f"  NV: packed=0x{packed_byte:02X} lo={lo_nib}({decoded_0}) hi={hi_nib}({decoded_1}) "
          f"bscale=0x{bscale_code:02X}({bscale_val}) tscale={tensor_scale} eff={eff_scale} "
          f"B=[{b0},{b1}] -> {prod_0}+{prod_1} = {result}")
    return result

def main():
    print("Computing MXFP4 test vectors:")
    mx_tests = [
        # (packed_byte, scale_code, b0, b1)
        (0xA3, 127, 0.5, 0.0),    # lo=3(+1.5), hi=A(-1.0), scale=1.0
        (0x42, 128, 0.5, 0.75),   # lo=2(+1.0), hi=4(+2.0), scale=2.0
        (0x15, 126, 1.0, 2.0),    # lo=5(+3.0), hi=1(+0.5), scale=0.5
        (0x00, 127, 1.0, 1.0),    # lo=0(+0.0), hi=0(+0.0), scale=1.0
        (0xE7, 127, 1.0, 1.0),    # lo=7(+6.0), hi=E(-4.0), scale=1.0
    ]
    mx_expected = []
    for t in mx_tests:
        exp = compute_mxfp4_mac(*t)
        mx_expected.append(exp)

    print("\nComputing NVFP4 test vectors:")
    nv_tests = [
        # (packed_byte, bscale_code, tensor_scale, b0, b1)
        (0x32, 0x38, 1.0, 2.0, 1.0),   # lo=2(+1.0), hi=3(+1.5), bscale=1.0
        (0x04, 0x40, 0.5, 3.0, 1.0),   # lo=4(+2.0), hi=0(+0.0), bscale=2.0
        (0xA9, 0x38, 2.0, 1.0, 1.0),   # lo=9(-0.5), hi=A(-1.0), bscale=1.0
    ]
    nv_expected = []
    for t in nv_tests:
        exp = compute_nvfp4_mac(*t)
        nv_expected.append(exp)

    # Write test_vectors.vh
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'test_vectors.vh')
