"""
gen_unified_vectors.py - Test vectors for unified dual-mode MAC
Tests both MXFP4 mode and NVFP4 mode through the same unit.
"""
import struct, os

def float_to_hex(f):
    return format(struct.unpack('>I', struct.pack('>f', f))[0], '08X')

E2M1 = {
    0x0: 0.0,  0x1: 0.5,  0x2: 1.0,  0x3: 1.5,
    0x4: 2.0,  0x5: 3.0,  0x6: 4.0,  0x7: 6.0,
    0x8: -0.0, 0x9: -0.5, 0xA: -1.0, 0xB: -1.5,
    0xC: -2.0, 0xD: -3.0, 0xE: -4.0, 0xF: -6.0,
}

def compute_mx(packed, scale_code, b0, b1):
    lo = packed & 0xF; hi = (packed >> 4) & 0xF
    d0 = E2M1[lo]; d1 = E2M1[hi]
    scale = 2.0 ** (scale_code - 127)
    return d0 * scale * b0 + d1 * scale * b1

def compute_nv(packed, bscale_code, tensor_scale, b0, b1):
    lo = packed & 0xF; hi = (packed >> 4) & 0xF
    d0 = E2M1[lo]; d1 = E2M1[hi]
    exp4 = (bscale_code >> 3) & 0xF
    man3 = bscale_code & 0x7
    sign = (bscale_code >> 7) & 1
    if exp4 == 0:
        bscale_val = (man3 / 8.0) * (2.0 ** (-6))
    else:
        bscale_val = (1.0 + man3 / 8.0) * (2.0 ** (exp4 - 7))
    if sign:
        bscale_val = -bscale_val
    eff = bscale_val * tensor_scale
    return d0 * eff * b0 + d1 * eff * b1

# (mode, packed, scale_a, scale_b, tensor_scale, b0, b1, description)
tests = []

# MXFP4 tests (mode=0)
print("MXFP4 mode tests:")
mx_cases = [
    (0xA3, 127, 0.5, 0.0,  "lo=3(+1.5) hi=A(-1.0) scale=1.0"),
    (0x42, 128, 0.5, 0.75, "lo=2(+1.0) hi=4(+2.0) scale=2.0"),
    (0x15, 126, 1.0, 2.0,  "lo=5(+3.0) hi=1(+0.5) scale=0.5"),
    (0x00, 127, 1.0, 1.0,  "zeros"),
    (0xE7, 127, 1.0, 1.0,  "lo=7(+6.0) hi=E(-4.0) scale=1.0"),
]
for packed, sc, b0, b1, desc in mx_cases:
    exp = compute_mx(packed, sc, b0, b1)
    tests.append((0, packed, sc, 0x00, 1.0, b0, b1, exp))
    print(f"  packed=0x{packed:02X} {desc} -> {exp}")

# NVFP4 tests (mode=1)
print("\nNVFP4 mode tests:")
nv_cases = [
    (0x32, 0x38, 1.0, 2.0, 1.0, "lo=2(+1.0) hi=3(+1.5) bscale=1.0"),
    (0x04, 0x40, 0.5, 3.0, 1.0, "lo=4(+2.0) hi=0(+0.0) bscale=2.0 ts=0.5"),
    (0xA9, 0x38, 2.0, 1.0, 1.0, "lo=9(-0.5) hi=A(-1.0) bscale=1.0 ts=2.0"),
]
for packed, scb, ts, b0, b1, desc in nv_cases:
    exp = compute_nv(packed, scb, ts, b0, b1)
    tests.append((1, packed, 0x00, scb, ts, b0, b1, exp))
    print(f"  packed=0x{packed:02X} {desc} -> {exp}")

# Write test_vectors.vh
N = len(tests)
out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'unified_test_vectors.vh')
with open(out_path, 'w') as f:
    f.write("// Auto-generated by gen_unified_vectors.py - DO NOT EDIT\n\n")
    f.write(f"localparam U_N = {N};\n")
    f.write(f"logic        u_mode    [{N}] = '{{" + ", ".join(f"1'b{t[0]}" for t in tests) + "};\n")
    f.write(f"logic [7:0]  u_packed  [{N}] = '{{" + ", ".join(f"8'h{t[1]:02X}" for t in tests) + "};\n")
    f.write(f"logic [7:0]  u_sca     [{N}] = '{{" + ", ".join(f"8'd{t[2]}" for t in tests) + "};\n")
    f.write(f"logic [7:0]  u_scb     [{N}] = '{{" + ", ".join(f"8'h{t[3]:02X}" for t in tests) + "};\n")
    f.write(f"logic [31:0] u_ts      [{N}] = '{{" + ", ".join(f"32'h{float_to_hex(t[4])}" for t in tests) + "};\n")
    f.write(f"logic [31:0] u_b0      [{N}] = '{{" + ", ".join(f"32'h{float_to_hex(t[5])}" for t in tests) + "};\n")
    f.write(f"logic [31:0] u_b1      [{N}] = '{{" + ", ".join(f"32'h{float_to_hex(t[6])}" for t in tests) + "};\n")
    f.write(f"logic [31:0] u_expected[{N}] = '{{" + ", ".join(f"32'h{float_to_hex(t[7])}" for t in tests) + "};\n")

print(f"\nGenerated: {out_path}")
print(f"\nExpected values:")
for i, t in enumerate(tests):
    mode = "MX" if t[0] == 0 else "NV"
    print(f"  [{i}] {mode} = {t[7]} = 0x{float_to_hex(t[7])}")
